    private void searchBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchBtnActionPerformed
        try{                                          
            if(MainOperations.isIdExists(idTxt.getText())){
                nicTxt.setText(MainOperations.findNic(idTxt.getText()));
                nameTxt.setText(MainOperations.findName(idTxt.getText()));
                int prfMark=MainOperations.findPrfMark(idTxt.getText());
                int dbmsMark=MainOperations.findDbmsMark(idTxt.getText());
                prfTxt.setText(prfMark==-1 ? "absent" : prfMark==-2 ? "not conducted" : Integer.toString(prfMark));
                dbmsTxt.setText(dbmsMark==-1 ? "absent" : dbmsMark==-2 ? "not conducted" : Integer.toString(dbmsMark));
                gpaTxt.setText(Double.toString(MainOperations.calculateGPA(prfMark, dbmsMark)));
            }else{
                JOptionPane.showMessageDialog(this,"This StudentId Does not exist in the system...");
                nicTxt.setText("");
                nameTxt.setText("");
                prfTxt.setText("");
                dbmsTxt.setText("");
                gpaTxt.setText("");
            }
        }catch(ClassNotFoundException ex){
            Logger.getLogger(ViewStudent.class.getName()).log(Level.SEVERE, null, ex);
        } catch (SQLException ex) {
            Logger.getLogger(ViewStudent.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }//GEN-LAST:event_searchBtnActionPerformed

