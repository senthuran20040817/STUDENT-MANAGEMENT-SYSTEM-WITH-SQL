    private void addBatchBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBatchBtnActionPerformed
        if(!batchNameTxt.getText().equals("") && !maxCountTxt.getText().equals("")){
            try {
                if(MainOperations.isBatchExists(batchNameTxt.getText())){
                    JOptionPane.showMessageDialog(this, "This Batch Already Exists in the system...");
                }else{
                    if(MainOperations.addBatch(batchNameTxt.getText(), Integer.parseInt(maxCountTxt.getText()))){
                        batchNameTxt.setEditable(false);
                        maxCountTxt.setEditable(false);
                        addBatchBtn.setEnabled(false);
                        JOptionPane.showMessageDialog(this, "Batch successfully added to the system...");
                        addBatchBtn.setEnabled(false);
                    }
                }
            } catch (ClassNotFoundException ex) {
                Logger.getLogger(AddBatch.class.getName()).log(Level.SEVERE, null, ex);
            } catch (SQLException ex) {
                Logger.getLogger(AddBatch.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_addBatchBtnActionPerformed

