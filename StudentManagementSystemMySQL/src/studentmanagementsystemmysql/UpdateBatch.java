    private void searchBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchBtnActionPerformed
        try{                                          
            if(MainOperations.isBatchExists(batchNameTxt.getText())){
                maxCountTxt.setEditable(true);
                batchNameTxt.setEditable(false);
                updateBatchBtn.setEnabled(true);
                searchBtn.setEnabled(false);
                enrolOpenRadioBtn.setEnabled(true);
                enrolCloseRadioBtn.setEnabled(true);
                
                studentCountTxt.setText(MainOperations.findStudentCount(batchNameTxt.getText()));
                oldStatus = MainOperations.findBatchStatus(batchNameTxt.getText());
                if(oldStatus==1){
                    enrolOpenRadioBtn.setSelected(true);
                }else if(oldStatus==0){
                    enrolCloseRadioBtn.setSelected(true);
                }
                oldMaxCount=MainOperations.findBatchMaxCount(batchNameTxt.getText());
                maxCountTxt.setText(oldMaxCount);
            }else{
                JOptionPane.showMessageDialog(this, "Invalid Batch Name...");
            }
            
        }catch(ClassNotFoundException ex){
            Logger.getLogger(UpdateBatch.class.getName()).log(Level.SEVERE, null, ex);
        } catch (SQLException ex) {
            Logger.getLogger(UpdateBatch.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_searchBtnActionPerformed

