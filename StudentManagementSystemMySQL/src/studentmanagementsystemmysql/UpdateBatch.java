    private void updateBatchBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBatchBtnActionPerformed
        int enrollment=1;
        if(enrolOpenRadioBtn.isSelected()){
                enrollment=1;
        }else if(enrolCloseRadioBtn.isSelected()){
                enrollment=0;
        }
        
        if(enrollment!=oldStatus || !maxCountTxt.getText().equals(oldMaxCount)){
            try {
                if(MainOperations.updateBatch(batchNameTxt.getText(),enrollment, Integer.parseInt(maxCountTxt.getText()))){
                    updateBatchBtn.setEnabled(false);
                    maxCountTxt.setEditable(false);
                    enrolOpenRadioBtn.setEnabled(false);
                    enrolCloseRadioBtn.setEnabled(false);
                    JOptionPane.showMessageDialog(this, "Batch Status Updated Successfully...");
                }
            } catch (ClassNotFoundException ex) {
                Logger.getLogger(UpdateBatch.class.getName()).log(Level.SEVERE, null, ex);
            } catch (SQLException ex) {
                Logger.getLogger(UpdateBatch.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_updateBatchBtnActionPerformed

