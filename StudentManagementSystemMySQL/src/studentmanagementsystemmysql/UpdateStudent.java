    private void updateStudentBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateStudentBtnActionPerformed
        searchBtn.setEnabled(false);
        idTxt.setEditable(false);
        if(!nameTxt.getText().equals(oldName) || !nicTxt.getText().equals(oldNic)){
            try {
                MainOperations.updateStudent(idTxt.getText(), nameTxt.getText(), nicTxt.getText());
                JOptionPane.showMessageDialog(this,"Student Details Updated Successfully...");
                updateStudentBtn.setEnabled(false);
                nameTxt.setEditable(false);
                nicTxt.setEditable(false);
            } catch (ClassNotFoundException ex) {
                Logger.getLogger(UpdateStudent.class.getName()).log(Level.SEVERE, null, ex);
            } catch (SQLException ex) {
                Logger.getLogger(UpdateStudent.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_updateStudentBtnActionPerformed

    private void searchBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchBtnActionPerformed
        try {
            if(MainOperations.isIdExists(idTxt.getText())){
                oldNic = MainOperations.findNic(idTxt.getText());
                nicTxt.setText(oldNic);
                oldName = MainOperations.findName(idTxt.getText());
                nameTxt.setText(oldName);
                
                nameTxt.setEditable(true);
                nicTxt.setEditable(true);
                updateStudentBtn.setEnabled(true);
            }else{
                JOptionPane.showMessageDialog(this,"This StudentId Does not exist in the system...");
                nameTxt.setText("");
                nicTxt.setText("");
            }
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(UpdateStudent.class.getName()).log(Level.SEVERE, null, ex);
        } catch (SQLException ex) {
            Logger.getLogger(UpdateStudent.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_searchBtnActionPerformed

