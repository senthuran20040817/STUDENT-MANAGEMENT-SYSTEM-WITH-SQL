    private void addStudentBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addStudentBtnActionPerformed
        try {
            int count = MainOperations.countStudent((String)batchNameComboBox.getSelectedItem());
            String id = (enrollmentTypeComboBox.getSelectedItem().equals("Physical") ? "PR" : "OR") + 24 + batchNameComboBox.getSelectedItem() + String.format("%03d",count);
            
            Student student = new Student(id, nicTxt.getText(), nameTxt.getText(), -2, -2);
            
            if(!nicTxt.getText().equals("") && !nameTxt.getText().equals("") && !batchNameComboBox.getSelectedItem().equals(batchNameArray[0]) && !enrollmentTypeComboBox.getSelectedItem().equals(enrollmentTypesArray[0])){
                int adding = MainOperations.addStudent(student);
                if(adding==0){
                    nameTxt.setEditable(false);
                    nicTxt.setEditable(false);
                    enrollmentTypeComboBox.setEnabled(false);
                    batchNameComboBox.setEnabled(false);
                    addStudentBtn.setEnabled(false);
                    JOptionPane.showMessageDialog(this,"Student Successfully Added...\nThe Id is --- "+id);
                }else if(adding==2){
                    JOptionPane.showMessageDialog(this,"This NIC No already exists...");
                }
            }
        } catch (ClassNotFoundException ex) {   
            Logger.getLogger(AddStudent.class.getName()).log(Level.SEVERE, null, ex);
        } catch (SQLException ex) {
            Logger.getLogger(AddStudent.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_addStudentBtnActionPerformed

