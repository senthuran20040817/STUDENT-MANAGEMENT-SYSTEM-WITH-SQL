    private void updateMarkBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateMarkBtnActionPerformed
        if(!newDbmsMarkTxt.getText().equals("")){
            try {
                if(MainOperations.dbmsMarkUpdate(idTxt.getText(), Integer.parseInt(newDbmsMarkTxt.getText()))){
                    newDbmsMarkTxt.setEditable(false);
                    updateMarkBtn.setEnabled(false );
                    JOptionPane.showMessageDialog(this, "DBMS Marks updated Successfully...");
                }
            } catch (ClassNotFoundException ex) {
                Logger.getLogger(DbmsMarkUpdate.class.getName()).log(Level.SEVERE, null, ex);
            } catch (SQLException ex) {
                Logger.getLogger(DbmsMarkUpdate.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_updateMarkBtnActionPerformed

