    private void searchBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchBtnActionPerformed
        try {
            String id=idTxt.getText();
            if(MainOperations.isIdExists(id)){
                int oldDbmsMark=MainOperations.findDbmsMark(id);
                idTxt.setEditable(false);
                searchBtn.setEnabled(false);
                updateMarkBtn.setEnabled(true);
                newDbmsMarkTxt.setEditable(true);
                nameTxt.setText(MainOperations.findName(id));
                nicTxt.setText(MainOperations.findNic(id));
                dbmsMarkTxt.setText(oldDbmsMark==-1 ? "absent" : oldDbmsMark==-2 ? "not conducted" : Integer.toString(oldDbmsMark));
            }else{
                JOptionPane.showMessageDialog(this, "Invalid Student ID");
            }
        } catch (ClassNotFoundException ex) {
            Logger.getLogger(DbmsMarkUpdate.class.getName()).log(Level.SEVERE, null, ex);
        } catch (SQLException ex) {
            Logger.getLogger(DbmsMarkUpdate.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_searchBtnActionPerformed

